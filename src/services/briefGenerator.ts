export function cleanBriefDocument(rawText: string, brandName?: string): string {
  if (!rawText) return '';

  let text = rawText.trim();

  // 1. Strip markdown code fence blocks if returned by model
  text = text.replace(/^```[a-z]*\s*\n?/im, '').replace(/\n?```\s*$/m, '');

  // 2. Strip AI conversational preamble
  text = text.replace(/^(?:Here (?:is|are)|Below is|Sure,?|Certainly!?|As requested|Thank you)[^\n]*\n+/i, '');

  // 3. Strip metadata headers at the top (e.g. Client Name:, Date:, Company:, Prepared For:, etc.)
  const firstSectionMatch = text.search(/(?:^|\n)(?:#+\s*)?1\.\s+/i);
  if (firstSectionMatch !== -1) {
    text = text.slice(firstSectionMatch).trim();
  } else {
    // If no numbered "1." header was found, strip leading metadata lines
    text = text.replace(/^(?:(?:\*\*|#+)?[ \t]*(?:Client(?:\s+Name)?|Brand(?:\s+Name)?|Company(?:\s+Name)?|Contact|Date|Status|Project(?:\s+Brief)?|Prepared\s+(?:for|by)|Website(?:\s+Summary)?):[^\n]*\n+)+/gi, '');
  }

  // 4. Remove all horizontal rules and separators (---, ***, ___, - - -, * * *)
  text = text.replace(/^[ \t]*[-*_]{3,}[ \t]*$/gm, '');
  text = text.replace(/^[ \t]*(\*[ \t]*){3,}$/gm, '');
  text = text.replace(/^[ \t]*(-[ \t]*){3,}$/gm, '');
  text = text.replace(/^[ \t]*(_[ \t]*){3,}$/gm, '');

  // 5. Remove any triple asterisks (***) or stray separator asterisks anywhere
  text = text.replace(/\*\*\*/g, '');

  // 6. Clean markdown headers (e.g. "### 1. WHAT..." -> "1. WHAT...")
  text = text.replace(/^[ \t]*#+[ \t]*/gm, '');

  // 7. Normalize bullet points to clean standard bullets: "* " or "- " -> "• "
  text = text.replace(/^[ \t]*[\*\-][ \t]+/gm, '• ');

  // 8. Strip trailing AI disclaimers or assistant remarks
  text = text.replace(/\n+(?:Please let me know|Feel free to reach out|I hope this helps|Generated by|Note: This summary is based|AI Generated)[^\n]*$/gi, '');

  // 9. Remove any residual lines that only contain punctuation/separators or metadata
  const lines = text.split('\n');
  const cleanedLines: string[] = [];

  for (const line of lines) {
    const trimmed = line.trim();
    if (/^[-*_~=]{2,}$/.test(trimmed)) {
      continue;
    }
    if (/^(?:Client\s+Name|Brand\s+Name|Project\s+Lead|Intake\s+Date|AI\s+Model):/i.test(trimmed)) {
      continue;
    }
    cleanedLines.push(line);
  }

  text = cleanedLines.join('\n');

  // 10. Clean excessive blank lines
  text = text.replace(/\n{3,}/g, '\n\n').trim();

  // 11. Normalize brand tagline to "Look Like You"
  text = text.replace(/about\s+things\s+finally\s+matching\.?/gi, 'to help your brand look like you.');
  text = text.replace(/things\s+finally\s+matching/gi, 'Look Like You');
  text = text.replace(/things\s+finally\s+match/gi, 'look like you');

  return text;
}

export function stripMarkdownFormatting(str: string): string {
  if (!str) return '';
  return str
    .replace(/\*\*\*(.*?)\*\*\*/g, '$1')
    .replace(/\*\*(.*?)\*\*/g, '$1')
    .replace(/\*(.*?)\*/g, '$1')
    .replace(/___(.*?)___/g, '$1')
    .replace(/__(.*?)__/g, '$1')
    .replace(/_(.*?)_/g, '$1')
    .replace(/\*\*\*/g, '')
    .replace(/^[ \t]*[-*_]{3,}[ \t]*$/gm, '')
    .trim();
}

/**
 * Generates a warm, plain-spoken, agency-grade Project Brief using Merakifos Brand Voice:
 * - Warm, plain spoken: "Your brand deserves to feel like you." No jargon anywhere.
 * - Quietly confident, not salesy: No exclamation points, no hype.
 * - Low pressure, reassuring: "A small, low risk way to start", "your accounts stay yours."
 * - Coherent, not fragmented: "Different hands, different feel... an easy fix. Look like you."
 */
export async function generateProjectBrief(answers: DiscoveryAnswers): Promise<string> {
  const brandName = answers.companyName || 'your brand';
  try {
    const res = await fetch('/api/generate-brief', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ answers }),
    });

    if (res.ok) {
      const data = await res.json();
      if (data.brief && data.brief.length > 100) {
        return cleanBriefDocument(data.brief, brandName);
      }
    }
  } catch (err) {
    console.warn('API brief generation fallback:', err);
  }

  // Merakifos brand voice fallback brief
  return cleanBriefDocument(buildMerakifosOnePageBrief(answers), brandName);
}

export function buildMerakifosOnePageBrief(answers: DiscoveryAnswers): string {
  const company = answers.companyName || 'your brand';
  const whatTheyDo = answers.businessAndClient || answers.businessSummary || 'thoughtful, meaningful work tailored to your favorite kind of clients';
  
  // Vibe from Q2
  const vibes = answers.brandVibe && answers.brandVibe.length > 0
    ? answers.brandVibe.join('; ')
    : 'Warm, grounded, and deeply personal';

  // Colors & visual taste from Question 4
  let colorsText = '';
  if (answers.selectedColors && answers.selectedColors.length > 0) {
    const paletteStr = answers.selectedColors.join(', ');
    const noteStr = answers.visualColors?.replace(/^Palette:\s*[^.]*(\.\s*Note:\s*)?/i, '').trim();
    colorsText = noteStr
      ? `Selected Palette [${paletteStr}]. Aesthetic nuances: ${noteStr}`
      : `Selected Palette [${paletteStr}]`;
  } else {
    colorsText = answers.visualColors?.trim() || 'A custom, intentional palette that reflects your authentic identity';
  }

  // Existing assets from Q4
  const assetsList = answers.existingAssets && answers.existingAssets.length > 0
    ? answers.existingAssets.map((a) => `• ${a}`).join('\n')
    : '• Building the visual foundation with care from the ground up';

  // Core objectives from Q5
  const objectivesList = answers.coreObjectives && answers.coreObjectives.length > 0
    ? answers.coreObjectives.map((o) => `• ${o}`).join('\n')
    : '• A clean, effortless digital home that presents your work with dignity and ease';

  // Inspiration sites from Q6
  const inspirationText = answers.inspirationSites?.trim()
    ? `Referencing the seamless flow, clarity, and mood of ${answers.inspirationSites.trim()}.`
    : 'Referencing clean, editorial, timeless design aesthetics.';

  // Success outcome from Q7
  const outcomeText = answers.successOutcome?.trim()
    ? answers.successOutcome.trim()
    : 'Attracting ideal clients effortlessly and feeling completely proud of your online presence.';

  // Timing & Budget from Q8
  const timingParts: string[] = [];
  if (answers.timelineSelection?.trim()) {
    timingParts.push(answers.timelineSelection.trim());
  }
  if (answers.customTimeline?.trim()) {
    timingParts.push(answers.customTimeline.trim());
  }
  const timingText = timingParts.length > 0
    ? timingParts.join(' — ')
    : (answers.targetLaunchWindow || 'Flexible / to be determined during discovery');

  const budgetParts: string[] = [];
  if (answers.budgetSelection?.trim()) {
    budgetParts.push(answers.budgetSelection.trim());
  }
  if (answers.customBudget?.trim()) {
    budgetParts.push(answers.customBudget.trim());
  }
  const budgetText = budgetParts.length > 0
    ? budgetParts.join(' — ')
    : (answers.budgetTier || 'Flexible / to be determined during discovery');

  return `1. WHAT YOU'RE BUILDING & WHO IT'S FOR
You're building ${company}.
${whatTheyDo}
In the first five seconds, visitors will immediately sense that: ${vibes}.

2. WHAT WE'LL PUT TOGETHER FOR YOU
Different hands, different feel... an easy fix. Our whole promise is helping your brand look like you.
We'll craft a complete, cohesive website tailored to your work:
• Core Platform Objectives:
${objectivesList}
• Toolkit & Assets Foundation:
${assetsList}
• Designed to look and feel natural across all phones, tablets, and computers
• Fast loading speeds, clean reading type, and basic search setup so people can find you

3. HOW IT WILL LOOK & FEEL
Your brand deserves to feel like you.
• Visual Mood & Aesthetic: ${vibes}.
• Palette & Tone: ${colorsText}.
• Aesthetic Touchstones: ${inspirationText}
Every font choice, color pairing, and bit of spacing will be shaped so visitors immediately sense the honesty and care behind what you do.

4. THE SIX-MONTH WIN (SUCCESS OUTCOME)
What makes hiring Merakifos the best decision you made this year:
"${outcomeText}"

5. INVESTMENT, TIMING & NEXT STEPS
• Timeline: ${timingText}.
• Investment Comfort Zone: ${budgetText}.
• A small, low risk way to start: Your accounts stay yours, and we take things one clear step at a time.
• Next Step: Take a look through this summary. If this feels like what you have in mind, approve it below and we'll schedule a time to chat.`;
}
